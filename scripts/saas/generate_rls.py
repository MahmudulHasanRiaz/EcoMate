#!/usr/bin/env python3
"""Generate PostgreSQL RLS policies and tenant guards from the proposed schema.

Usage:
  python3 scripts/saas/generate_rls.py \
    --schema apps/backend/prisma/schema.tenant.prisma \
    --out apps/backend/prisma/migrations-saas/0002_rls_and_tenant_guards/migration.sql
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from analyze_schema import GLOBAL_REFERENCE_MODELS, LICENSE_MODELS, parse_models  # noqa: E402


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--schema", default="apps/backend/prisma/schema.tenant.prisma", type=Path
    )
    parser.add_argument(
        "--out",
        default="apps/backend/prisma/migrations-saas/0002_rls_and_tenant_guards/migration.sql",
        type=Path,
    )
    args = parser.parse_args()

    models = parse_models(args.schema.read_text())
    tenant_models = [
        model
        for model in models
        if model.name not in GLOBAL_REFERENCE_MODELS
        and model.name not in LICENSE_MODELS
        and "tenantId" in model.fields
    ]
    tenant_models.sort(key=lambda model: model.table)

    lines: list[str] = []
    lines.append("-- EcoMate SaaS tenant isolation: RLS policies + write guards.")
    lines.append("-- Generated by scripts/saas/generate_rls.py from schema.tenant.prisma.")
    lines.append("--")
    lines.append("-- This migration does NOT create a login role with a password.")
    lines.append("-- The deployment provisioner creates `ecomate_app` (NOSUPERUSER,")
    lines.append("-- NOBYPASSRLS) and sets its credentials out of band. Migrations and")
    lines.append("-- controlled backfills run as the owner/migrator role.")
    lines.append("")
    lines.append("BEGIN;")
    lines.append("")
    lines.append("-- The current tenant is carried on the connection by the tenant pool:")
    lines.append("--   options = '-c app.tenant_id=<tenant-uuid>'")
    lines.append("-- An unset/empty setting makes both reads and writes fail closed.")
    lines.append("CREATE OR REPLACE FUNCTION enforce_tenant_id() RETURNS trigger AS $$")
    lines.append("DECLARE")
    lines.append("  ctx text;")
    lines.append("BEGIN")
    lines.append("  ctx := NULLIF(current_setting('app.tenant_id', true), '');")
    lines.append("  IF ctx IS NULL OR ctx = '' THEN")
    lines.append("    RAISE EXCEPTION 'tenant context missing';")
    lines.append("  END IF;")
    lines.append("  NEW.tenant_id := ctx::uuid;")
    lines.append("  RETURN NEW;")
    lines.append("END;")
    lines.append("$$ LANGUAGE plpgsql;")
    lines.append("")
    lines.append("DO $$")
    lines.append("BEGIN")
    lines.append("  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'ecomate_app') THEN")
    lines.append("    CREATE ROLE ecomate_app NOLOGIN NOSUPERUSER NOBYPASSRLS;")
    lines.append("  END IF;")
    lines.append("  EXECUTE 'GRANT USAGE ON SCHEMA public TO ecomate_app';")
    lines.append("  EXECUTE 'GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA public TO ecomate_app';")
    lines.append("  EXECUTE 'GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO ecomate_app';")
    lines.append("  EXECUTE 'ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO ecomate_app';")
    lines.append("  EXECUTE 'ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT USAGE, SELECT ON SEQUENCES TO ecomate_app';")
    lines.append("END $$;")
    lines.append("")

    for model in tenant_models:
        table = model.table
        lines.append(f"-- {model.name} -> {table}")
        lines.append(f'ALTER TABLE "{table}" ENABLE ROW LEVEL SECURITY;')
        lines.append(f'ALTER TABLE "{table}" FORCE ROW LEVEL SECURITY;')
        lines.append(f'DROP POLICY IF EXISTS tenant_isolation ON "{table}";')
        lines.append(
            f'CREATE POLICY tenant_isolation ON "{table}"'
        )
        lines.append(
            "  USING (tenant_id = (NULLIF(current_setting('app.tenant_id', true), ''))::uuid)"
        )
        lines.append(
            "  WITH CHECK (tenant_id = (NULLIF(current_setting('app.tenant_id', true), ''))::uuid);"
        )
        lines.append(f'DROP TRIGGER IF EXISTS tenant_id_guard ON "{table}";')
        lines.append(
            f'CREATE TRIGGER tenant_id_guard BEFORE INSERT OR UPDATE ON "{table}"'
        )
        lines.append("  FOR EACH ROW EXECUTE FUNCTION enforce_tenant_id();")
        lines.append("")

    lines.append("-- RLS coverage view used by CI and the boot-time check.")
    lines.append("-- A row with tenant_scoped=true and any of rls_enabled/rls_forced/")
    lines.append("-- has_policy/has_trigger false is a deployment-blocking gap.")
    lines.append("CREATE OR REPLACE VIEW rls_coverage AS")
    lines.append("SELECT c.relname AS table_name,")
    lines.append(
        "       EXISTS (SELECT 1 FROM information_schema.columns col"
    )
    lines.append(
        "               WHERE col.table_schema = 'public'"
    )
    lines.append(
        "                 AND col.table_name = c.relname"
    )
    lines.append(
        "                 AND col.column_name = 'tenant_id') AS tenant_scoped,"
    )
    lines.append("       c.relrowsecurity AS rls_enabled,")
    lines.append("       c.relforcerowsecurity AS rls_forced,")
    lines.append(
        "       EXISTS (SELECT 1 FROM pg_policies p"
    )
    lines.append(
        "               WHERE p.schemaname = 'public'"
    )
    lines.append(
        "                 AND p.tablename = c.relname"
    )
    lines.append(
        "                 AND p.policyname = 'tenant_isolation') AS has_policy,"
    )
    lines.append(
        "       EXISTS (SELECT 1 FROM pg_trigger t"
    )
    lines.append(
        "               WHERE t.tgrelid = c.oid"
    )
    lines.append(
        "                 AND t.tgname = 'tenant_id_guard'"
    )
    lines.append(
        "                 AND NOT t.tgisinternal) AS has_trigger"
    )
    lines.append("FROM pg_class c")
    lines.append("JOIN pg_namespace n ON n.oid = c.relnamespace")
    lines.append("WHERE n.nspname = 'public'")
    lines.append("  AND c.relkind = 'r'")
    lines.append("  AND c.relname <> '_prisma_migrations';")
    lines.append("")
    lines.append("COMMIT;")
    lines.append("")

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("\n".join(lines))
    print(
        f"generated {args.out} with {len(tenant_models)} tenant tables"
    )


if __name__ == "__main__":
    main()
